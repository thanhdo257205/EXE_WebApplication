CREATE TABLE admin_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feedback_id UUID NOT NULL UNIQUE REFERENCES player_feedback(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE admin_notification_reads (
    notification_id BIGINT NOT NULL REFERENCES admin_notifications(id),
    user_id UUID NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    read_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (notification_id, user_id)
);
CREATE INDEX ix_notification_reads_user ON admin_notification_reads(user_id, notification_id);
